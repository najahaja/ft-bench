"""Pydantic schema for the FT-Bench NLU task.

Output shape: {"intent": <one of 60 MASSIVE intents>,
               "slots": {<slot_type>: <verbatim substring>, ...}}

Vocabulary is loaded from configs/label_vocab.json, which is itself
generated by scripts/prepare_dataset.py from the MASSIVE dataset — it is
never hand-written here.
"""
import json
import re
from pathlib import Path
from typing import Optional, Tuple

from pydantic import BaseModel, field_validator

_VOCAB_PATH = Path(__file__).resolve().parents[2] / "configs" / "label_vocab.json"


def _load_vocab() -> dict:
    with open(_VOCAB_PATH) as f:
        return json.load(f)


class NLUParse(BaseModel):
    intent: str
    slots: dict[str, str]

    @field_validator("intent")
    @classmethod
    def intent_in_vocab(cls, v: str) -> str:
        vocab = _load_vocab()
        allowed = vocab.get("intents", [])
        if allowed and v not in allowed:
            raise ValueError(f"intent '{v}' not in MASSIVE vocabulary")
        return v

    @field_validator("slots")
    @classmethod
    def slot_keys_in_vocab(cls, v: dict[str, str]) -> dict[str, str]:
        vocab = _load_vocab()
        allowed = vocab.get("slots", [])
        if allowed:
            for key in v:
                if key not in allowed:
                    raise ValueError(f"slot type '{key}' not in MASSIVE vocabulary")
        return v


def extract_json_block(text: str) -> str:
    """Extract first JSON object from model output, handling markdown fences."""
    text = text.strip()
    if "```json" in text:
        text = text.split("```json")[1].split("```")[0].strip()
    elif "```" in text:
        parts = text.split("```")
        if len(parts) >= 3:
            text = parts[1].strip()
    match = re.search(r"\{[^{}]*(?:\{[^{}]*\}[^{}]*)*\}", text, re.DOTALL)
    if match:
        return match.group(0)
    return text


def validate_output(output_str: str) -> Tuple[bool, Optional[NLUParse], Optional[str]]:
    """
    Parses and validates model output as an NLUParse.
    Returns (is_valid, parsed_model_or_None, error_message_or_None).
    """
    try:
        cleaned = extract_json_block(output_str)
        data = json.loads(cleaned)
        model = NLUParse(**data)
        return True, model, None
    except json.JSONDecodeError as e:
        return False, None, f"JSONDecodeError: {e}"
    except Exception as e:
        return False, None, f"ValidationError: {e}"
